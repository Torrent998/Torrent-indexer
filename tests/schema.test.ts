import { readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { z } from "zod";
import { eventsResponseSchema, reconciliationEventSchema } from "../src/http/server.js";

/** The public boundary, as JSON Schema. Update with `UPDATE_GOLDEN=1 npm test -- schema`. */
const doc = () =>
  JSON.stringify(
    {
      $comment: "Generated by tests/schema.test.ts from src/http/server.ts. Do not edit by hand.",
      "x-schemaVersion": 1,
      endpoint: "GET /v1/ledger/events?cursor=&limit=",
      response: z.toJSONSchema(eventsResponseSchema),
      reconciliationEvent: z.toJSONSchema(reconciliationEventSchema),
    },
    null,
    2,
  ) + "\n";

describe("generated JSON Schema snapshot", () => {
  const path = new URL("../generated/ledger-events.schema.json", import.meta.url);
  it("matches the committed file (schema changes need a version decision)", () => {
    if (process.env["UPDATE_GOLDEN"]) writeFileSync(path, doc());
    expect(readFileSync(path, "utf8")).toBe(doc());
  });
});
